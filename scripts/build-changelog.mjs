#!/usr/bin/env node
// Reads the root CHANGELOG.md, parses it with the shared library, and emits a
// typed TypeScript module at viewer/src/lib/changelog.generated.ts.
// The viewer imports the module synchronously; no markdown parser ships in the
// runtime bundle. Build aborts with an actionable error on missing/malformed input.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseChangelog } from "./check-changelog-lib.mjs";

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CHANGELOG_PATH = resolve(REPO_ROOT, "CHANGELOG.md");
const OUT_PATH = resolve(REPO_ROOT, "viewer/src/lib/changelog.generated.ts");

function fail(message) {
	process.stderr.write(`build-changelog: ${message}\n`);
	process.exit(1);
}

function main() {
	if (!existsSync(CHANGELOG_PATH)) {
		fail(`CHANGELOG.md not found at repository root (${CHANGELOG_PATH}). Create it before building the viewer.`);
	}
	const source = readFileSync(CHANGELOG_PATH, "utf8");
	let parsed;
	try {
		parsed = parseChangelog(source);
	} catch (err) {
		fail(`failed to parse ${CHANGELOG_PATH}: ${err.message}`);
	}

	const banner =
		"// This file is generated by scripts/build-changelog.mjs from the root CHANGELOG.md.\n" +
		"// Do not edit by hand; changes will be overwritten on the next viewer build.\n" +
		"// Regenerate with: node scripts/build-changelog.mjs\n";

	const body =
		`import type { ParsedChangelog } from "./changelog";\n\n` +
		`export const CHANGELOG_DATA: ParsedChangelog = ${JSON.stringify(parsed, null, 2)} as const;\n`;

	mkdirSync(dirname(OUT_PATH), { recursive: true });
	writeFileSync(OUT_PATH, `${banner}\n${body}`, "utf8");
	process.stdout.write(`build-changelog: wrote ${OUT_PATH} (${parsed.releases.length} releases)\n`);
}

main();
